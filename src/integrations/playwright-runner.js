import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { now } from '../core/util.js';

const ANSI = /\u001b\[[0-9;]*m/g;

/**
 * Runs a generated Playwright suite in a child process (isolated from the
 * orchestrator), with a hard timeout, and returns normalized results parsed
 * from Playwright's JSON reporter.
 */
export class PlaywrightRunner {
  constructor({ rootDir, timeoutMs, testTimeoutMs, workers, simulate }) {
    this.cli = path.join(rootDir, 'node_modules', '@playwright', 'test', 'cli.js');
    this.timeoutMs = timeoutMs;
    this.testTimeoutMs = testTimeoutMs;
    this.workers = workers;
    this.simulate = simulate || !fs.existsSync(this.cli);
  }

  get mode() {
    return this.simulate ? 'simulated' : 'playwright';
  }

  /**
   * @param suiteDir  folder with the spec files (a run's generated suite or the test library)
   * @param outDir    where config, report and artifacts go (defaults to suiteDir)
   * @param grep      only tests whose title or tags match (e.g. "@smoke")
   * @param filter    file or file:line filter, relative to suiteDir
   */
  async run({ suiteDir, outDir = suiteDir, grep = null, filter = null, baseUrl, variables = {}, signal, log }) {
    const startedAt = now();
    if (this.simulate) return this.#simulated({ suiteDir, grep, filter, startedAt });

    fs.mkdirSync(outDir, { recursive: true });
    const reportPath = path.join(outDir, 'report.json');
    const configPath = path.join(outDir, 'playwright.config.mjs');
    fs.writeFileSync(
      configPath,
      `// Generated by ORCA. Do not edit.
export default {
  testDir: ${JSON.stringify(suiteDir)},
  testMatch: /.*\\.spec\\.mjs$/,
  timeout: ${this.testTimeoutMs},
  expect: { timeout: 4000 },
  retries: 0,
  workers: ${this.workers},
  outputDir: ${JSON.stringify(path.join(outDir, 'artifacts'))},
  reporter: [['json', { outputFile: ${JSON.stringify(reportPath)} }]],
  use: { baseURL: ${JSON.stringify(baseUrl)}, headless: true, screenshot: 'only-on-failure', trace: 'retain-on-failure', actionTimeout: 4000 },
  projects: [{ name: 'chromium', use: { browserName: 'chromium' } }],
};
`,
    );
    fs.rmSync(reportPath, { force: true });

    const { code, stderr } = await new Promise((resolve, reject) => {
      const args = [this.cli, 'test', '-c', configPath];
      if (grep) args.push('--grep', grep);
      if (filter) args.push(filter);
      const child = spawn(process.execPath, args, {
        cwd: suiteDir,
        // Only the selected environment's variables reach the tests, never ORCA's own secrets.
        env: { ...pickEnv(process.env), ...variables, CI: '1', FORCE_COLOR: '0' },
        stdio: ['ignore', 'pipe', 'pipe'],
      });
      let err = '';
      child.stdout.on('data', (d) => log?.debug(String(d).trim()));
      child.stderr.on('data', (d) => (err += d));
      const timer = setTimeout(() => child.kill('SIGKILL'), this.timeoutMs);
      const onAbort = () => child.kill('SIGKILL');
      signal?.addEventListener('abort', onAbort, { once: true });
      child.on('error', reject);
      child.on('close', (c) => {
        clearTimeout(timer);
        signal?.removeEventListener('abort', onAbort);
        resolve({ code: c, stderr: err });
      });
    });

    if (!fs.existsSync(reportPath)) {
      throw Object.assign(new Error(`Playwright produced no report (exit ${code}): ${stderr.replace(ANSI, '').slice(0, 500)}`), { retryable: false });
    }
    const report = JSON.parse(fs.readFileSync(reportPath, 'utf8'));
    const results = [];
    const visit = (suite, file) => {
      for (const spec of suite.specs || []) {
        for (const t of spec.tests || []) {
          const r = t.results?.[t.results.length - 1] || {};
          const err = r.error || r.errors?.[0];
          results.push({
            testId: (spec.title.match(/\[([A-Z][A-Z0-9]*-\d+-AC\d+)\]/) || [])[1] || spec.title,
            title: spec.title.replace(/^\[[^\]]+\]\s*/, '').replace(/(?:^|\s)@[\w-]+(?=\s|$)/g, ' ').replace(/\s+/g, ' ').trim(),
            file: spec.file || file,
            status: r.status || (t.status === 'skipped' ? 'skipped' : 'failed'),
            durationMs: r.duration || 0,
            startedAt: r.startTime ? new Date(r.startTime).toISOString() : null,
            error: err ? { message: clean(err.message), stack: clean(err.stack), snippet: clean(err.snippet) } : null,
            attachments: (r.attachments || []).filter((a) => a.path).map((a) => ({ name: a.name, path: path.relative(outDir, a.path), contentType: a.contentType })),
          });
        }
      }
      for (const child of suite.suites || []) visit(child, suite.file || file);
    };
    (report.suites || []).forEach((s) => visit(s, s.file));
    for (const e of report.errors || []) {
      results.push({ testId: 'suite-error', title: 'Suite failed to load', file: '', status: 'failed', durationMs: 0, error: { message: clean(e.message) }, attachments: [] });
    }
    return { startedAt, finishedAt: now(), mode: 'playwright', results, rawReportPath: reportPath };
  }

  /** Fallback when Playwright is not installed: marks every matching test as skipped. */
  #simulated({ suiteDir, grep, filter, startedAt }) {
    const onlyFile = filter ? filter.replace(/:\d+$/, '') : null;
    const results = fs
      .readdirSync(suiteDir, { recursive: true })
      .map((f) => String(f).split(path.sep).join('/'))
      .filter((f) => f.endsWith('.spec.mjs') && (!onlyFile || f === onlyFile))
      .flatMap((file) => {
        const source = fs.readFileSync(path.join(suiteDir, file), 'utf8');
        if (grep && !source.includes(grep)) return [];
        return [...source.matchAll(/test(?:\.fixme)?\(\s*'(?:\[([^\]]+)\]\s*)?([^']*)'/g)].map((m) => ({
          testId: m[1] || m[2], title: m[2], file, status: 'skipped', durationMs: 0, error: null, attachments: [],
        }));
      });
    return { startedAt, finishedAt: now(), mode: 'simulated', results, rawReportPath: null };
  }
}

function clean(s) {
  return s ? String(s).replace(ANSI, '') : undefined;
}

/** Child processes only get a minimal environment: no API keys or tokens leak into tests. */
function pickEnv(env) {
  const allow = ['PATH', 'HOME', 'TMPDIR', 'LANG', 'PLAYWRIGHT_BROWSERS_PATH', 'SystemRoot', 'USERPROFILE', 'APPDATA', 'LOCALAPPDATA'];
  return Object.fromEntries(allow.filter((k) => env[k]).map((k) => [k, env[k]]));
}
