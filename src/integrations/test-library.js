import fs from 'node:fs';
import path from 'node:path';
import { execFile } from 'node:child_process';

const SPEC = /\.spec\.(mjs|js|ts)$/;
const STR = String.raw`(['"\x60])((?:\\.|(?!\1).)*)\1`;
const DESCRIBE = new RegExp(String.raw`\btest\.describe(?:\.\w+)?\(\s*${STR}\s*(?:,\s*\{([^}]*)\})?`);
// Same as STR, but the quote is group 2 because group 1 is the modifier.
const TEST = new RegExp(String.raw`\btest(?:\.(fixme|skip|only|fail))?\(\s*(['"\x60])((?:\\.|(?!\2).)*)\2\s*(?:,\s*\{([^}]*)\})?`);
const TITLE_TAG = /(?:^|\s)(@[A-Za-z0-9][\w-]*)(?=\s|$)/g;
const OPTION_TAG = /['"\x60](@[A-Za-z0-9][\w-]*)['"\x60]/g;
const TICKET_TAG = /^@[A-Z][A-Z0-9]+-\d+$/;
const CASE_ID = /^\[([^\]]+)\]\s*/;

/**
 * The team's Playwright test library: every spec file kept in the repo
 * (qa-tests/ by default). Hand-written tests live next to the tests OrcaStrator
 * generates for each ticket (tickets/<KEY>/), and tags group them into suites
 * such as @smoke and @regression, which can be run on demand.
 *
 * Suites are described in <library>/suites.json:
 *   { "suites": [{ "name": "smoke", "tag": "@smoke", "description": "…" }] }
 * Any other tag found in the specs shows up as a suite too.
 *
 * The list of tests comes from Playwright itself (`playwright test --list`), so
 * loops, multi-line titles, inherited describe tags and skipped tests read
 * exactly as Playwright sees them. It is cached until a spec file changes. When
 * the Playwright CLI is missing or a spec cannot be loaded, a static parse of
 * the sources is used instead and the catalog says why.
 */
export class TestLibrary {
  /**
   * @param dir      the library folder
   * @param cli      Playwright's cli.js; without it the static parser is used
   * @param workDir  where the generated list config is written
   */
  constructor({ dir, cli = null, workDir = null, timeoutMs = 60_000 }) {
    this.dir = dir;
    this.cli = cli && fs.existsSync(cli) ? path.resolve(cli) : null;
    this.workDir = workDir;
    this.timeoutMs = timeoutMs;
    this.cache = null; // { key, value }
    this.pending = null; // { key, promise }
  }

  /**
   * Catalog of the library: { dir, files, suites, tests, source, errors }.
   * source is 'playwright' (listed by Playwright) or 'static' (parsed from the sources).
   */
  async catalog() {
    const files = this.#specFiles();
    const key = this.#cacheKey(files);
    if (this.cache?.key === key) return this.cache.value;
    if (this.pending?.key !== key) {
      const promise = this.#build(files).then((value) => {
        if (this.pending?.promise === promise) {
          this.cache = { key, value };
          this.pending = null;
        }
        return value;
      });
      this.pending = { key, promise };
    }
    return this.pending.promise;
  }

  async #build(files) {
    let tests = null;
    let source = 'playwright';
    let errors = [];
    if (!this.cli) {
      source = 'static';
      errors = ['Playwright is not installed, so tests were read from the sources.'];
    } else if (files.length) {
      try {
        tests = await this.#listWithPlaywright();
      } catch (err) {
        source = 'static';
        errors = err.listErrors || [err.message];
      }
    }
    tests ??= files.flatMap((file) => parseSpec(file, fs.readFileSync(path.join(this.dir, file), 'utf8')));
    const declared = this.#declaredSuites();
    const counts = new Map();
    for (const t of tests) for (const tag of t.tags) if (!TICKET_TAG.test(tag)) counts.set(tag, (counts.get(tag) || 0) + 1);
    const suites = declared.map((s) => ({ ...s, count: counts.get(s.tag) || 0 }));
    for (const [tag, count] of counts) if (!suites.some((s) => s.tag === tag)) suites.push({ name: tag.slice(1), tag, description: '', count });
    return { dir: this.dir, files, suites, tests, source, errors };
  }

  /** Asks Playwright for the test list (nothing runs; no browser starts). */
  async #listWithPlaywright() {
    const workDir = this.workDir || path.join(this.dir, '.orca');
    fs.mkdirSync(workDir, { recursive: true });
    const configPath = path.join(workDir, 'list.config.mjs');
    fs.writeFileSync(
      configPath,
      `// Generated by OrcaStrator to list the test library. Do not edit.\n` +
        `export default { testDir: ${JSON.stringify(this.dir)}, testMatch: ${SPEC}, testIgnore: ['**/node_modules/**'] };\n`,
    );
    const stdout = await new Promise((resolve, reject) => {
      execFile(
        process.execPath,
        [this.cli, 'test', '-c', configPath, '--list', '--reporter=json'],
        { cwd: this.dir, timeout: this.timeoutMs, maxBuffer: 64 * 1024 * 1024, env: { ...process.env, FORCE_COLOR: '0' } },
        (err, out, stderr) => {
          // A load error exits 1 but still prints a JSON report that names it.
          if (out && out.trim().startsWith('{')) return resolve(out);
          reject(new Error(err ? `Playwright could not list the tests: ${(stderr || err.message).trim().split('\n')[0]}` : 'Playwright returned no list'));
        },
      );
    });
    const report = JSON.parse(stdout);
    if (report.errors?.length) {
      const roots = [...new Set([this.dir, fs.realpathSync(this.dir)])].map((d) => d + path.sep);
      const listErrors = report.errors.map((e) => roots.reduce((msg, r) => msg.split(r).join(''), String(e.message || e).split('\n')[0]));
      throw Object.assign(new Error(listErrors[0]), { listErrors });
    }
    return fromListReport(report);
  }

  #cacheKey(files) {
    const stamp = (f) => {
      try {
        return fs.statSync(path.join(this.dir, f)).mtimeMs;
      } catch {
        return 0;
      }
    };
    return [...files, 'suites.json'].map((f) => `${f}@${stamp(f)}`).join('|');
  }

  /** Playwright --grep for a suite name ("all" runs everything). */
  async grepFor(suite) {
    if (!suite || suite === 'all') return null;
    const s = (await this.catalog()).suites.find((x) => x.name === suite || x.tag === suite);
    if (!s) throw Object.assign(new Error(`Unknown suite "${suite}"`), { status: 400 });
    return s.tag;
  }

  /** Source of one spec file, confined to the library. */
  read(file) {
    return fs.readFileSync(this.resolve(file), 'utf8');
  }

  /** Writes a spec into the library (used to keep generated ticket tests). */
  write(file, source) {
    const target = this.resolve(file);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, source);
    return path.relative(this.dir, target);
  }

  /** Replaces the generated tests of one ticket. */
  clearTicket(ticketKey) {
    fs.rmSync(this.resolve(path.join('tickets', ticketKey)), { recursive: true, force: true });
  }

  resolve(file) {
    const target = path.resolve(this.dir, String(file));
    if (target !== this.dir && !target.startsWith(this.dir + path.sep)) throw Object.assign(new Error('Path outside the test library'), { status: 400 });
    return target;
  }

  #specFiles() {
    if (!fs.existsSync(this.dir)) return [];
    return fs
      .readdirSync(this.dir, { recursive: true })
      .map(String)
      .filter((f) => SPEC.test(f) && !f.split(path.sep).some((part) => part === 'node_modules' || part === '.orca'))
      .map((f) => f.split(path.sep).join('/'))
      .sort();
  }

  #declaredSuites() {
    try {
      const json = JSON.parse(fs.readFileSync(path.join(this.dir, 'suites.json'), 'utf8'));
      return (json.suites || [])
        .filter((s) => s && /^@[\w-]+$/.test(s.tag))
        .map((s) => ({ name: String(s.name || s.tag.slice(1)), tag: s.tag, description: String(s.description || '') }));
    } catch {
      return [];
    }
  }
}

/** Maps Playwright's `--list --reporter=json` report to catalog tests (one entry per test, whatever the projects). */
export function fromListReport(report) {
  const tests = [];
  const seen = new Map();
  const walk = (suite, describe) => {
    for (const spec of suite.specs || []) {
      const file = String(spec.file).split(path.sep).join('/');
      const base = `${file}:${spec.line}`;
      const n = (seen.get(base) || 0) + 1;
      seen.set(base, n);
      const runs = spec.tests || [];
      const skipped = runs.length > 0 && runs.every((t) => t.expectedStatus === 'skipped' || (t.annotations || []).some((a) => a.type === 'fixme' || a.type === 'skip'));
      const tags = [...new Set([...(spec.tags || []).map((t) => (t.startsWith('@') ? t : `@${t}`))])];
      const ticketTag = tags.find((t) => TICKET_TAG.test(t));
      tests.push({
        // Tests made in a loop share a line; the id stays unique.
        id: n === 1 ? base : `${base}#${n}`,
        file,
        line: spec.line,
        caseId: (spec.title.match(CASE_ID) || [])[1] || null,
        title: cleanTitle(spec.title),
        fullTitle: spec.title,
        describe,
        tags,
        ticketKey: ticketTag ? ticketTag.slice(1) : null,
        state: skipped ? 'not-automated' : 'active',
      });
    }
    for (const child of suite.suites || []) walk(child, child.title || describe);
  };
  // Top-level suites are files; their child suites are describe blocks.
  for (const fileSuite of report.suites || []) walk(fileSuite, null);
  return tests.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
}

function cleanTitle(raw) {
  return raw.replace(CASE_ID, '').replace(TITLE_TAG, ' ').replace(/\s+/g, ' ').trim();
}

/** Finds test() calls with their titles, tags and describe block. The fallback when Playwright cannot list the tests. */
export function parseSpec(file, source) {
  const tests = [];
  let describe = null;
  let describeTags = [];
  source.split('\n').forEach((line, i) => {
    const d = line.match(DESCRIBE);
    if (d) {
      describe = d[2];
      describeTags = tagsOf(d[2], d[3]);
      return;
    }
    const m = line.match(TEST);
    if (!m) return;
    const rawTitle = m[3];
    const caseId = (rawTitle.match(CASE_ID) || [])[1] || null;
    const title = cleanTitle(rawTitle);
    const tags = [...new Set([...describeTags, ...tagsOf(rawTitle, m[4])])];
    const ticketTag = tags.find((t) => TICKET_TAG.test(t));
    tests.push({
      id: `${file}:${i + 1}`,
      file,
      line: i + 1,
      caseId,
      title,
      fullTitle: rawTitle,
      describe,
      tags,
      ticketKey: ticketTag ? ticketTag.slice(1) : null,
      state: m[1] === 'fixme' || m[1] === 'skip' ? 'not-automated' : 'active',
    });
  });
  return tests;
}

function tagsOf(title, options) {
  return [...String(title).matchAll(TITLE_TAG), ...String(options || '').matchAll(OPTION_TAG)].map((m) => m[1]);
}
