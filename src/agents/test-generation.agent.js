import fs from 'node:fs';
import path from 'node:path';
import { z } from 'zod';
import { BaseAgent } from '../core/agent.js';
import { RequirementAnalysis, TestGenerationResult } from '../core/contracts.js';

const SYSTEM = `You are a senior SDET writing Playwright tests (JavaScript, ESM, @playwright/test).
For each acceptance criterion write the BODY of one async test function that receives { page, request }.
Rules:
- Use only page.getByTestId(...) with the data-testid values provided, page.getByText, page.goto with relative paths, and request.get/post/put/delete for APIs.
- Use web-first assertions (await expect(locator).toHaveText(...), toBeVisible, toHaveURL).
- Do not import anything, do not use require, fs, process, child_process, eval or network calls other than page/request.
- Keep one assertion per "Then"/"And" outcome; never weaken an expected value from the criterion.`;

const FORBIDDEN = /\b(require\s*\(|import\s|child_process|process\.|eval\s*\(|Function\s*\(|fs\.)/;

/**
 * Test Generation Agent
 * Turns acceptance criteria (plus code context: selectors and routes found in
 * the application source) into executable Playwright UI and API tests.
 */
export class TestGenerationAgent extends BaseAgent {
  constructor() {
    super({
      id: 'test-generation',
      name: 'Test Generation Agent',
      description: 'Designs and generates automated UI and API tests from tickets, acceptance criteria and existing code.',
      tags: ['generation', 'playwright'],
    });

    this.action(
      'generate',
      { input: z.object({ analysis: RequirementAnalysis, runId: z.string() }), output: TestGenerationResult, description: 'Generate Playwright tests' },
      async ({ analysis, runId }, ctx) => {
        const knownIds = await ctx.integrations.codeContext.findTestIds().catch(() => []);
        const routes = await ctx.integrations.codeContext.findRoutes().catch(() => []);
        ctx.log.info(`Code context: ${knownIds.length} data-testid selectors, ${routes.length} routes`);

        const suiteDir = path.join(ctx.config.paths.workspace, 'runs', runId, 'tests');
        fs.mkdirSync(suiteDir, { recursive: true });

        let llmBodies = {};
        if (ctx.llm.available) {
          llmBodies = await this.#llmBodies(analysis, knownIds, routes, ctx).catch((err) => {
            ctx.log.warn(`LLM generation failed, using step compiler: ${err.message}`);
            return {};
          });
        }

        const tests = [];
        const files = [];
        let usedLlm = false;
        for (const req of analysis.requirements) {
          if (!req.acceptanceCriteria.length) continue;
          const file = `${req.id}.spec.mjs`;
          const blocks = [];
          for (const ac of req.acceptanceCriteria) {
            const compiled = compileCriterion(ac, knownIds.map((k) => k.id));
            let body = compiled.lines.join('\n');
            const llmBody = llmBodies[ac.id];
            if (llmBody && !FORBIDDEN.test(llmBody)) {
              body = llmBody;
              usedLlm = true;
            } else if (llmBody) {
              ctx.log.warn(`Discarded LLM test for ${ac.id}: forbidden API usage`);
            }
            const kind = compiled.kind;
            const fn = compiled.unsupported.length && !llmBody ? 'test.fixme' : 'test';
            blocks.push(
              `  ${fn}(${quote(`[${ac.id}] ${ac.title}`)}, async ({ page, request }) => {\n` +
                (compiled.unsupported.length && !llmBody ? `    // ORCA could not automate: ${compiled.unsupported.join(' | ')}\n` : '') +
                indent(body, 4) +
                `\n  });`,
            );
            tests.push({
              id: ac.id,
              requirementId: req.id,
              acceptanceCriterionId: ac.id,
              title: ac.title,
              kind,
              file,
              code: body,
              unsupportedSteps: llmBody ? [] : compiled.unsupported,
              warnings: compiled.warnings,
            });
          }
          const source = `// Generated by ORCA Test Generation Agent for ${analysis.ticketKey} / ${req.id}\n// ${req.title}\nimport { test, expect } from '@playwright/test';\n\ntest.describe(${quote(`${req.id} ${req.title}`)}, () => {\n${blocks.join('\n\n')}\n});\n`;
          fs.writeFileSync(path.join(suiteDir, file), source);
          files.push(file);
        }

        const result = { ticketKey: analysis.ticketKey, suiteDir, files, tests, source: usedLlm ? 'llm' : 'heuristic' };
        ctx.memory.run.set('generatedTests', result);
        ctx.trace(
          tests.map((t) => ({ id: `test:${t.id}`, type: 'test', label: t.title, data: { file: t.file, kind: t.kind, warnings: t.warnings, unsupported: t.unsupportedSteps } })),
          tests.map((t) => ({ from: t.acceptanceCriterionId, to: `test:${t.id}`, rel: 'verified_by' })),
        );
        const warnings = tests.reduce((n, t) => n + t.warnings.length, 0);
        ctx.log.info(`Generated ${tests.length} test(s) in ${files.length} file(s)${warnings ? `, ${warnings} warning(s)` : ''}`);
        return result;
      },
    );
  }

  async #llmBodies(analysis, knownIds, routes, ctx) {
    const criteria = analysis.requirements.flatMap((r) => r.acceptanceCriteria);
    if (!criteria.length) return {};
    const out = await ctx.llm.generateObject({
      system: SYSTEM,
      prompt:
        `Application routes:\n${routes.join('\n') || '(unknown)'}\n\nKnown data-testid selectors:\n${knownIds.map((k) => `${k.id} (${k.file})`).join('\n') || '(unknown)'}\n\n` +
        `Login macro for "I am logged in": goto /login, fill login-email "demo@orca.dev", login-password "orca123", click login-submit, wait for URL /dashboard.\n\n` +
        `Acceptance criteria:\n${JSON.stringify(criteria, null, 2)}`,
      schema: z.object({ tests: z.array(z.object({ acceptanceCriterionId: z.string(), body: z.string() })) }),
    });
    return Object.fromEntries(out.tests.map((t) => [t.acceptanceCriterionId, t.body]));
  }
}

// ---------------------------------------------------------------------------
// Deterministic step compiler (used offline and as the fallback for the LLM)
// ---------------------------------------------------------------------------

const pagePath = (name) => (name.startsWith('/') ? name : name === 'home' ? '/' : `/${name}`);
const quote = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const indent = (s, n) => s.split('\n').map((l) => (l ? ' '.repeat(n) + l : l)).join('\n');

const STEPS = [
  {
    re: /^I am logged in$/i,
    ui: true,
    ids: ['login-email', 'login-password', 'login-submit'],
    code: () => [
      `await page.goto('/login');`,
      `await page.getByTestId('login-email').fill('demo@orca.dev');`,
      `await page.getByTestId('login-password').fill('orca123');`,
      `await page.getByTestId('login-submit').click();`,
      `await expect(page).toHaveURL(/\\/dashboard/);`,
    ],
  },
  { re: /^I am on the "([^"]+)" page$/i, ui: true, code: ([p]) => [`await page.goto(${quote(pagePath(p))});`] },
  { re: /^I fill "([^"]+)" with "([^"]*)"$/i, ui: true, sel: 0, code: ([id, v]) => [`await page.getByTestId(${quote(id)}).fill(${quote(v)});`] },
  { re: /^I click "([^"]+)"$/i, ui: true, sel: 0, code: ([id]) => [`await page.getByTestId(${quote(id)}).click();`] },
  { re: /^I should see "([^"]+)"$/i, ui: true, code: ([t]) => [`await expect(page.getByText(${quote(t)})).toBeVisible();`] },
  { re: /^I should be on the "([^"]+)" page$/i, ui: true, code: ([p]) => [`await expect(page).toHaveURL(new RegExp(${quote(pagePath(p).replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '$')}));`] },
  { re: /^"([^"]+)" should show "([^"]*)"$/i, ui: true, sel: 0, code: ([id, t]) => [`await expect(page.getByTestId(${quote(id)})).toHaveText(${quote(t)});`] },
  {
    re: /^I send an? (GET|POST|PUT|PATCH|DELETE) request to "([^"]+)"(?: with body (.+))?$/i,
    api: true,
    code: ([m, url, body]) => [`res = await request.${m.toLowerCase()}(${quote(url)}${body ? `, { data: ${body} }` : ''});`, `body = await res.json().catch(() => null);`],
  },
  { re: /^the response status should be (\d{3})$/i, api: true, code: ([s]) => [`expect(res.status()).toBe(${Number(s)});`] },
  { re: /^the response should contain (\d+) items?$/i, api: true, code: ([n]) => [`expect(Array.isArray(body) ? body : body.items).toHaveLength(${Number(n)});`] },
  {
    re: /^each item should have (.+)$/i,
    api: true,
    code: ([list]) => {
      const fields = [...list.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
      return [`for (const item of Array.isArray(body) ? body : body.items) {`, ...fields.map((f) => `  expect(item).toHaveProperty(${quote(f)});`), `}`];
    },
  },
  { re: /^the response field "([^"]+)" should be "([^"]*)"$/i, api: true, code: ([f, v]) => [`expect(body?.${f.replace(/[^\w.]/g, '')}).toBe(${quote(v)});`] },
];

export function compileCriterion(ac, knownIds = []) {
  const lines = [];
  const unsupported = [];
  const warnings = [];
  let api = false;
  let ui = false;
  const sections = [['Given', ac.given], ['When', ac.when], ['Then', ac.then]];
  for (const [kw, steps] of sections) {
    steps.forEach((step, i) => {
      lines.push(`// ${i === 0 ? kw : 'And'} ${step}`);
      const match = STEPS.map((s) => ({ s, m: step.match(s.re) })).find((x) => x.m);
      if (!match) {
        unsupported.push(step);
        lines.push(`// TODO: unsupported step`);
        return;
      }
      const args = match.m.slice(1);
      if (match.s.api) api = true;
      if (match.s.ui) ui = true;
      const ids = match.s.ids || (match.s.sel !== undefined ? [args[match.s.sel]] : []);
      for (const id of ids) {
        if (knownIds.length && !knownIds.includes(id)) {
          const similar = knownIds.filter((k) => k.includes(id) || id.includes(k) || distance(k, id) <= 3);
          warnings.push(`Selector data-testid="${id}" was not found in the application source${similar.length ? ` (similar: ${similar.join(', ')})` : ''}.`);
        }
      }
      lines.push(...match.s.code(args));
    });
  }
  if (api) lines.unshift('let res;', 'let body;');
  return { lines, unsupported, warnings, kind: api && !ui ? 'api' : 'ui' };
}

function distance(a, b) {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++)
    for (let j = 1; j <= b.length; j++) dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
  return dp[a.length][b.length];
}
